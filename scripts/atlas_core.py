"""Read and validate Atlas documentation; no firmware or upstream code is run."""
from __future__ import annotations

import copy
import datetime as dt
import json
import math
import re
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator, FormatChecker

KINDS = {"camera": "cameras", "firmware": "firmware", "project": "projects",
         "capability": "capabilities", "evidence": "evidence", "source": "sources",
         "community": "community", "reference": "reference"}
TECHNICAL_TOPICS = ("platform", "patching", "tooling", "emulation", "colour", "capture", "interfaces")
ADDRESS_CATEGORIES = ("function", "hook-site", "data", "table", "free-space", "layout")
TRAIT_CATEGORIES = ("platform", "native-feature")  # one fact about one build, keyed by trait or feature, no address
TRAIT_FIELDS = ("trait", "feature_id", "presence", "value")
REFERENCE_FILE_BUDGET = 16000  # bytes per records/reference file: split by build or topic beyond this
# Detail that belongs upstream, not in a reference entry (see maintenance/reference-policy.md).
UPSTREAM_ONLY = (
    (re.compile(r"```"), "code blocks"),
    (re.compile(r"\b(?:call|calls|mov|movbu|movhu|jmp|retf|cmp|bra)\s+\S+,\s*\S", re.I), "disassembly"),
    (re.compile(r"\b(?:[0-9a-fA-F]{2}[ :]){7,}[0-9a-fA-F]{2}\b"), "byte dumps"),
    (re.compile(r"(?<![x0-9a-fA-F])[0-9a-fA-F]{24,}\b"), "long hex runs"),
)


def reference_status(records, row):
    """Derived, never hand-set: disputed, camera-confirmed, corroborated or single-source."""
    if row.get("conflicts"):
        return "disputed"
    observations = row.get("observations", [])
    if any(o["method"] == "physical-camera" for o in observations):
        return "camera-confirmed"
    repos = {records.get(o["source_ref"], {}).get("upstream_repo") or o["source_ref"] for o in observations}
    return "corroborated" if len(repos) >= 2 else "single-source"
REPO = "https://github.com/xulfr/om-firmware-atlas"
GENERATED = "<!-- Generated by scripts/atlas.py. Edit canonical records/metadata, then regenerate. -->\n\n"
LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")


def normalise(value):
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    if isinstance(value, dict):
        return {k: normalise(v) for k, v in value.items()}
    if isinstance(value, list):
        return [normalise(v) for v in value]
    return value


def read_yaml(path):
    return normalise(yaml.safe_load(path.read_text(encoding="utf-8")))


def read_article(path):
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n", text, re.S)
    if not match:
        raise ValueError(f"{path}: add the required YAML front matter (see templates/topic.md).")
    return normalise(yaml.safe_load(match.group(1))), text[match.end():]


def slug(node_id):
    return node_id.split(".", 1)[1]


def link(origin, target):
    import os
    return Path(os.path.relpath(target, Path(origin).parent)).as_posix()


def cost(path):
    size = path.stat().st_size
    return size, math.ceil(size / 4)


def without_code(text):
    return re.sub(r"```.*?```", "", text, flags=re.S)


class Catalogue:
    def __init__(self, root):
        self.root = Path(root).resolve()
        self.records = {}
        self.paths = {}
        self.articles = {}
        self.errors = []
        self.taxonomy = read_yaml(self.root / "taxonomy/topics.yaml")
        self.jobs = read_yaml(self.root / "agents/jobs.yaml")["jobs"]
        schema = json.loads((self.root / "schemas/records.schema.json").read_text(encoding="utf-8"))
        Draft202012Validator.check_schema(schema)
        header = copy.deepcopy(schema)
        header["properties"]["records"]["items"] = {"type": "object"}
        for path in sorted((self.root / "records").rglob("*.yaml")):
            rel = path.relative_to(self.root).as_posix()
            try:
                data = read_yaml(path)
            except (ValueError, yaml.YAMLError) as exc:
                self.errors.append(f"{rel}: invalid YAML: {exc}")
                continue
            self.errors.extend(self.schema_errors(header, data, rel))
            if rel.startswith("records/reference/") and path.stat().st_size > REFERENCE_FILE_BUDGET:
                self.errors.append(f"{rel}: over {REFERENCE_FILE_BUDGET} bytes; split reference entries by build or topic so agents can load one shard.")
            if not isinstance(data, dict) or not isinstance(data.get("records"), list):
                continue
            for row in data["records"]:
                if not isinstance(row, dict):
                    continue
                kind = row.get("type")
                if kind not in KINDS:
                    self.errors.append(f"{rel}: choose a known record type: {', '.join(KINDS)}.")
                    continue
                selected = {"$ref": f"#/$defs/{kind}", "$defs": schema["$defs"]}
                self.errors.extend(self.schema_errors(selected, row, f"{rel} [{row.get('id', '?')}]"))
                node_id = row.get("id")
                if not isinstance(node_id, str):
                    continue
                if node_id in self.records:
                    self.errors.append(f"{rel}: duplicate ID {node_id}; preserve one canonical record.")
                self.records[node_id] = row
                self.paths[node_id] = rel
                if path.relative_to(self.root / "records").parts[0] != KINDS[kind]:
                    self.errors.append(f"{rel}: move {node_id} into records/{KINDS[kind]}/.")
        article_schema = json.loads((self.root / "schemas/article.schema.json").read_text(encoding="utf-8"))
        for path in sorted((self.root / "knowledge").rglob("*.md")):
            if path.name == "README.md":
                continue
            rel = path.relative_to(self.root).as_posix()
            try:
                meta, body = read_article(path)
            except (ValueError, yaml.YAMLError) as exc:
                self.errors.append(str(exc))
                continue
            self.errors.extend(self.schema_errors(article_schema, meta, rel))
            if not isinstance(meta, dict) or not isinstance(meta.get("id"), str):
                continue
            node_id = meta["id"]
            if node_id in self.articles or node_id in self.records:
                self.errors.append(f"{rel}: duplicate ID {node_id}.")
            self.articles[node_id] = dict(meta, path=rel, body=body)

    @staticmethod
    def schema_errors(schema, data, label):
        validator = Draft202012Validator(schema, format_checker=FormatChecker())
        return [f"{label} {'.'.join(map(str, e.absolute_path)) or '<record>'}: {e.message}"
                for e in sorted(validator.iter_errors(data), key=lambda e: str(e.absolute_path))]

    def of_type(self, kind):
        return sorted((v for v in self.records.values() if v.get("type") == kind), key=lambda r: r["id"])

    def ref(self, node_id, expected=None):
        row = self.records.get(node_id)
        return row if row and (expected is None or row.get("type") == expected) else None

    def validate(self):
        errors = list(self.errors)
        if errors:
            return sorted(set(errors))
        refs = {"camera_id": "camera", "firmware_id": "firmware", "project_id": "project", "source_ref": "source"}
        lists = {"camera_ids": "camera", "project_ids": "project", "related_projects": "project",
                 "source_refs": "source", "evidence_refs": "evidence", "contradicting_refs": "evidence"}

        def check_ref(owner, field, target, kind):
            if target is not None and not self.ref(target, kind):
                errors.append(f"{owner}: {field} references missing/wrong-type {target}; add a {kind} record or fix the ID.")

        for node_id, row in self.records.items():
            for field, kind in refs.items():
                check_ref(node_id, field, row.get(field), kind)
            for field, kind in lists.items():
                for target in row.get(field, []):
                    check_ref(node_id, field, target, kind)
            for target in row.get("supersedes", []):
                check_ref(node_id, "supersedes", target, row["type"])
                if target == node_id:
                    errors.append(f"{node_id}: cannot supersede itself.")
            for topic in row.get("topics", []):
                if topic not in self.taxonomy["topics"]:
                    errors.append(f"{node_id}: unknown topic {topic}; use taxonomy/topics.yaml.")
            if row["type"] != "source" and not row.get("source_refs"):
                errors.append(f"{node_id}: add a source_refs entry; do not publish an unsourced assertion.")
            firmware = self.ref(row.get("firmware_id"), "firmware")
            if firmware and firmware["camera_id"] != row.get("camera_id"):
                errors.append(f"{node_id}: firmware {firmware['id']} belongs to {firmware['camera_id']}, not {row.get('camera_id')}; fix target scope.")
            if row["type"] == "source" and row.get("source_kind") == "github-file":
                revision = row.get("revision") or ""
                if not re.fullmatch(r"[0-9a-f]{40}", revision) or f"/blob/{revision}/" not in row.get("url", ""):
                    errors.append(f"{node_id}: pin github-file URL and revision to the same full 40-character commit.")
            if row["type"] == "reference":
                errors.extend(self.reference_errors(node_id, row, check_ref))
            if row["type"] == "project":
                for feature in row.get("features", []):
                    label = f"feature '{feature['name']}'"
                    check_ref(node_id, f"{label} source_ref", feature["source_ref"], "source")
                    for camera in feature["camera_ids"]:
                        if camera not in row["camera_ids"]:
                            errors.append(f"{node_id}: {label} names {camera}, which is not in the project's camera_ids; add the camera or narrow the feature.")
                    if feature.get("capability_id"):
                        capability = self.ref(feature["capability_id"], "capability")
                        if not capability:
                            check_ref(node_id, f"{label} capability_id", feature["capability_id"], "capability")
                        elif capability["project_id"] != node_id:
                            errors.append(f"{node_id}: {label} links {capability['id']}, which belongs to another project.")
                dates = [release["date"] for release in row.get("releases", [])]
                if dates != sorted(dates, reverse=True):
                    errors.append(f"{node_id}: list releases newest first.")
                tags = [release["tag"] for release in row.get("releases", [])]
                if len(tags) != len(set(tags)):
                    errors.append(f"{node_id}: duplicate release tag; keep one entry per release.")
                for release in row.get("releases", []):
                    if row["url"].startswith("https://github.com/"):
                        expected_url = f"{row['url'].rstrip('/')}/releases/tag/{release['tag']}"
                        if release["url"] != expected_url:
                            errors.append(f"{node_id}: release {release['tag']} must link to {expected_url}.")
                    check_ref(node_id, f"release {release['tag']} source_ref", release["source_ref"], "source")
                    for camera in release["camera_ids"]:
                        if camera not in row["camera_ids"]:
                            errors.append(f"{node_id}: release {release['tag']} names {camera}, which is not in the project's camera_ids.")
                for image in row.get("images", []):
                    if not (self.root / "docs" / image["path"]).is_file():
                        errors.append(f"{node_id}: image docs/{image['path']} does not exist.")
            if row["type"] == "capability":
                if row.get("feature_id") not in self.taxonomy["features"]:
                    errors.append(f"{node_id}: add feature_id to taxonomy/features or select an existing feature.")
                for evidence_id in row.get("evidence_refs", []) + row.get("contradicting_refs", []):
                    evidence = self.ref(evidence_id, "evidence")
                    if evidence:
                        for field in ("camera_id", "firmware_id", "project_id", "mod_build"):
                            if evidence.get(field) != row.get(field):
                                errors.append(f"{node_id}: {evidence_id} has different {field}; select matching evidence or narrow the assertion.")
            if row["type"] == "evidence":
                if row.get("identity_level") in ("release-label-only", "not-applicable") and row.get("package_sha256"):
                    errors.append(f"{node_id}: a label-only/not-applicable identity cannot supply a reported/observed package hash; keep expected_package_sha256 separate.")
                if row.get("identity_level") in ("reported-hash", "observed-hash") and not row.get("package_sha256"):
                    errors.append(f"{node_id}: hash identity requires package_sha256 from the report/observation, not an expected manifest hash.")
                if row.get("method") == "emulator" and not row.get("emulator"):
                    errors.append(f"{node_id}: emulator evidence needs repo, revision, model and named stand-ins.")
                if row.get("quality") == "complete" and row.get("method") == "physical-camera":
                    for field in ("camera_id", "firmware_id", "mod_build", "package_sha256", "procedure", "tested_on"):
                        if not row.get(field):
                            errors.append(f"{node_id}: complete physical report requires {field}; mark quality partial if unknown.")
                    if row.get("identity_level") not in ("reported-hash", "observed-hash"):
                        errors.append(f"{node_id}: complete physical report requires a reported/observed hash identity.")
                if row.get("tested_on") and row.get("reported_on") and row["tested_on"] > row["reported_on"]:
                    errors.append(f"{node_id}: tested_on is after reported_on; correct the date or record it as unknown.")
        seen = {}
        for row in self.of_type("reference"):
            address = row.get("address")
            if address:
                key = (row["firmware_ids"][0], address["space"], address["value"])
                if key in seen:
                    errors.append(f"{row['id']}: same build and address as {seen[key]}; merge them and add an observation instead.")
                seen[key] = row["id"]
            if row["category"] in TRAIT_CATEGORIES and row["firmware_ids"]:
                key = (row["firmware_ids"][0], row["category"], row.get("trait") or row.get("feature_id"))
                if key in seen:
                    errors.append(f"{row['id']}: same build and {row['category']} fact as {seen[key]}; merge them and add an observation instead.")
                seen[key] = row["id"]
        for node_id, article in self.articles.items():
            for field, kind in lists.items():
                for target in article.get(field, []):
                    check_ref(node_id, field, target, kind)
            for topic in article.get("topics", []):
                if topic not in self.taxonomy["topics"]:
                    errors.append(f"{node_id}: unknown topic {topic}.")

        def visit(node_id, stack):
            if node_id in stack:
                errors.append(f"{node_id}: dependency cycle {' -> '.join(stack + [node_id])}; remove the cyclic dependency.")
                return
            if node_id not in self.articles:
                errors.append(f"{node_id}: dependency does not resolve to a knowledge guide.")
                return
            if len(stack) >= 3:
                errors.append(f"{node_id}: dependency path exceeds three guides; flatten the chain.")
                return
            for target in self.articles[node_id].get("depends_on", []):
                visit(target, stack + [node_id])

        for node_id in self.articles:
            visit(node_id, [])
        for job, config in self.jobs.items():
            for field in ("role", "workflow"):
                path = config.get(field)
                if path and not (self.root / path).is_file():
                    errors.append(f"Job {job}: {field} path {path} does not exist.")
        return sorted(set(errors))

    def reference_errors(self, node_id, row, check_ref):
        errors = []
        for field in ("camera_ids", "firmware_ids"):
            for target in row[field]:
                check_ref(node_id, field, target, field[:-4])
        for firmware_id in row["firmware_ids"]:
            firmware = self.ref(firmware_id, "firmware")
            if firmware and firmware["camera_id"] not in row["camera_ids"]:
                errors.append(f"{node_id}: {firmware_id} belongs to {firmware['camera_id']}, which is not in camera_ids.")
        if row["category"] in ADDRESS_CATEGORIES:
            if "address" not in row:
                errors.append(f"{node_id}: a {row['category']} entry needs an address.")
            if len(row["firmware_ids"]) != 1:
                errors.append(f"{node_id}: an address belongs to exactly one firmware build; make one entry per build.")
            if row["category"] == "free-space" and "end" not in row.get("address", {}):
                errors.append(f"{node_id}: free space needs an end address.")
        elif row["category"] in TRAIT_CATEGORIES:
            if "address" in row:
                errors.append(f"{node_id}: a {row['category']} entry describes a build; put addresses in their own entries.")
            if len(row["firmware_ids"]) != 1:
                errors.append(f"{node_id}: a {row['category']} entry describes exactly one firmware build; make one entry per build.")
            if row["category"] == "platform":
                if row.get("trait") not in self.taxonomy.get("traits", {}):
                    errors.append(f"{node_id}: choose a trait from taxonomy/topics.yaml traits.")
                if not row.get("value"):
                    errors.append(f"{node_id}: a platform entry needs a value.")
                if row.get("feature_id") or row.get("presence"):
                    errors.append(f"{node_id}: a platform entry takes trait and value, not feature_id or presence.")
            else:
                if row.get("feature_id") not in self.taxonomy["features"]:
                    errors.append(f"{node_id}: choose a feature_id from taxonomy/topics.yaml features.")
                if not row.get("presence"):
                    errors.append(f"{node_id}: a native-feature entry needs a presence.")
                if row.get("trait"):
                    errors.append(f"{node_id}: a native-feature entry takes feature_id and presence, not trait.")
        else:
            if "address" in row:
                errors.append(f"{node_id}: a hazard states a rule; put addresses in their own per-build entries.")
            if not row.get("consequence"):
                errors.append(f"{node_id}: a hazard needs its observed or expected consequence.")
        if row["category"] not in TRAIT_CATEGORIES and any(field in row for field in TRAIT_FIELDS):
            errors.append(f"{node_id}: trait, feature_id, presence and value belong to platform and native-feature entries.")
        repos = set()
        for item in row["observations"] + row["conflicts"]:
            source = self.ref(item["source_ref"], "source")
            check_ref(node_id, "observation source_ref", item["source_ref"], "source")
            if item.get("project_id"):
                check_ref(node_id, "observation project_id", item["project_id"], "project")
            if source:
                repos.add(source.get("upstream_repo"))
                if item["source_ref"] not in row.get("source_refs", []):
                    errors.append(f"{node_id}: add {item['source_ref']} to source_refs.")
                if not (source.get("revision") or source.get("content_sha256")):
                    errors.append(f"{node_id}: {item['source_ref']} is not pinned; cite a revision or a content digest for technical reference.")
        if not any(repo and row["upstream_detail"].startswith(f"https://github.com/{repo}/") for repo in repos):
            errors.append(f"{node_id}: upstream_detail must link the detailed section in a cited source's repository.")
        texts = [row["title"], row["summary"], row["note"], row.get("consequence", ""), row.get("value", "")]
        texts += [item["summary"] for item in row["observations"] + row["conflicts"]]
        for pattern, kind in UPSTREAM_ONLY:
            if any(pattern.search(text) for text in texts):
                errors.append(f"{node_id}: contains {kind}; keep that detail upstream and link it with upstream_detail.")
        return errors

    def resolve_camera(self, selector):
        if selector in self.records and self.records[selector]["type"] == "camera":
            return selector
        key = re.sub(r"[^a-z0-9]", "", selector.lower())
        matches = []
        for row in self.of_type("camera"):
            labels = [slug(row["id"]), row["title"], *row["aliases"], *row["model_codes"]]
            if any(re.sub(r"[^a-z0-9]", "", value.lower()) == key for value in labels):
                matches.append(row["id"])
        if len(matches) != 1:
            choices = ", ".join(matches) if matches else "see agents/routes/cameras/index.md"
            raise ValueError(f"Camera '{selector}' is {'ambiguous' if matches else 'not catalogued'}: {choices}. Use an exact camera ID.")
        return matches[0]

    def reading_plan(self, job, camera=None, topic=None, project=None, source=None):
        if job not in self.jobs:
            raise ValueError(f"Unknown job '{job}'; choose {', '.join(self.jobs)}.")
        config = self.jobs[job]
        plan = ["AGENTS.md", "agents/start.md", config["role"]]
        if config.get("workflow"):
            plan.append(config["workflow"])
        camera_id = self.resolve_camera(camera) if camera else None
        if source and not project:
            candidates = [r for r in self.of_type("project") if source.rstrip("/").startswith(r["url"].rstrip("/") + "/") or source.rstrip("/") == r["url"].rstrip("/")]
            if candidates:
                project = max(candidates, key=lambda r: len(r["url"]))["id"]
        if camera_id:
            plan.append(f"agents/routes/cameras/{slug(camera_id)}.md")
            shard = f"agents/routes/reference/{slug(camera_id)}.md"
            if topic in TECHNICAL_TOPICS and (self.root / shard).is_file():
                plan.append(shard)
        if project:
            project_id = project if project.startswith("project.") else "project." + project
            if not self.ref(project_id, "project"):
                raise ValueError(f"Project '{project}' is not catalogued; use the project index and ingestion workflow.")
            plan.append(f"agents/routes/projects/{slug(project_id)}.md")
        if topic:
            if topic not in self.taxonomy["topics"]:
                raise ValueError(f"Unknown topic '{topic}'; use agents/routes/topics/index.md.")
            plan.append(f"agents/routes/topics/{topic}.md")
        elif job == "community":
            topic = "community"
            plan.append("agents/routes/topics/community.md")
        if not camera_id and not project and not topic:
            plan.append("agents/routes/projects/index.md" if job in ("ingest", "freshness") else "agents/routes/cameras/index.md")

        def add_article(node_id):
            article = self.articles[node_id]
            if camera_id and article.get("camera_ids") and camera_id not in article["camera_ids"]:
                return
            for dep in article.get("depends_on", []):
                add_article(dep)
            plan.append(article["path"])

        if topic:
            for node_id, article in sorted(self.articles.items()):
                if topic in article["topics"]:
                    add_article(node_id)
        return list(dict.fromkeys(plan))


def markdown_links(root):
    errors = []
    paths = [root / x for x in ("README.md", "AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md")]
    for directory in ("docs", "knowledge", "agents", "maintenance", "templates", "views"):
        paths.extend((root / directory).rglob("*.md"))
    for path in paths:
        if not path.exists():
            errors.append(f"Missing entry document {path.relative_to(root)}.")
            continue
        text = without_code(path.read_text(encoding="utf-8"))
        for target in LINK_RE.findall(text):
            if target.startswith(("https://", "http://", "mailto:", "#")):
                continue
            destination = (path.parent / target.split("#", 1)[0]).resolve()
            if not destination.is_relative_to(root) or not destination.exists():
                errors.append(f"{path.relative_to(root)}: broken local link {target}; fix the target or add its canonical file.")
    return errors


def routing_checks(catalogue):
    errors = []
    cases = read_yaml(catalogue.root / "maintenance/routing-cases/cases.yaml")["cases"]
    for case in cases:
        try:
            plan = catalogue.reading_plan(**case["request"])
        except ValueError as exc:
            if case.get("expect_error") and case["expect_error"] in str(exc):
                continue
            errors.append(f"Routing {case['id']}: {exc}")
            continue
        if case.get("expect_error"):
            errors.append(f"Routing {case['id']}: expected {case['expect_error']} but accepted the request.")
        for required in case.get("required", []):
            if required not in plan:
                errors.append(f"Routing {case['id']}: missing required {required}.")
        for forbidden in case.get("forbidden", []):
            if any(forbidden in path for path in plan):
                errors.append(f"Routing {case['id']}: read forbidden bulk/unrelated path {forbidden}.")
        for before, after in case.get("ordered", []):
            if before not in plan or after not in plan or plan.index(before) >= plan.index(after):
                errors.append(f"Routing {case['id']}: {before} must precede {after}.")
        route_cost = sum(cost(catalogue.root / path)[1] for path in plan if not path.startswith("knowledge/"))
        if route_cost > case.get("max_routing_tokens", 2500):
            errors.append(f"Routing {case['id']}: approx {route_cost} tokens exceeds {case['max_routing_tokens']}; shrink/split routes.")
    return errors
